"""Shell: focus model, menu bar, palette, help, reset, theme, hint bar, toasts."""
from playwright.sync_api import sync_playwright, expect
from common import Console, check, expect_value, focus, goto_tab, join, launch, shot

with sync_playwright() as p:
    b = launch(p)
    page = b.new_page(viewport={"width": 1400, "height": 900})
    con = Console(page, "shell")
    join(page, "alice")
    active = lambda: page.evaluate("document.activeElement.dataset.control || document.activeElement.id || document.activeElement.tagName")

    # focus: sidebar → Enter → first control; Tab / Shift+Tab; Shift+Tab from the first → sidebar; Esc → sidebar
    check(active() == "sidebar", "the sidebar has focus on join")
    page.keyboard.press("Enter")
    check(active() == "text.name", "Enter moves into the tab body (first control)")
    page.keyboard.press("Tab")
    check(active() == "text.email", "Tab: next control")
    page.keyboard.press("Tab")
    page.keyboard.press("Tab")
    check(active() == "password", "Tab reaches the password field")
    page.keyboard.press("Shift+Tab")
    page.keyboard.press("Shift+Tab")
    page.keyboard.press("Shift+Tab")
    check(active() == "text.name", "Shift+Tab: previous control")
    page.keyboard.press("Shift+Tab")
    check(active() == "sidebar", "Shift+Tab from the first control returns to the sidebar")
    page.keyboard.press("Tab")
    page.keyboard.press("Escape")
    check(active() == "sidebar", "Esc with no popup returns to the sidebar")
    page.keyboard.press("F6")
    check(active() == "text.name", "F6 toggles into the body")
    page.keyboard.press("F6")
    check(active() == "sidebar", "F6 toggles back")
    check("Enter" in page.locator(".hintbar").inner_text(), "hint bar shows the sidebar's keys")

    # menu bar: F10, ←/→, Esc; Alt+H opens Help
    page.keyboard.press("F10")
    expect(page.locator("[data-popup='menu']")).to_be_visible()
    check(page.locator("[data-popup='menu']").inner_text().startswith("Reset this tab"), "F10 opens File")
    page.keyboard.press("ArrowRight")
    expect(page.locator("[data-popup='menu']")).to_contain_text("Gantt")
    check(True, "→ moves to View (the 16 tabs)")
    shot(page, "shell-menu-view")
    page.keyboard.press("Escape")
    expect(page.locator("[data-popup='menu']")).to_have_count(0)
    page.keyboard.press("Alt+KeyH")
    expect(page.locator("[data-popup='menu']")).to_contain_text("About")
    page.keyboard.press("End")
    page.keyboard.press("Enter")
    expect(page.locator("[data-popup='dialog']")).to_contain_text("rust 0.5.0")
    check(True, "Alt+H ▸ About shows server and client versions")
    page.keyboard.press("Escape")
    expect(page.locator("[data-popup='dialog']")).to_have_count(0)

    # View ▸ Theme ▸ Gruvbox by mouse (submenu on hover)
    page.click(".menubar.top [data-menu='View']")
    page.hover("[data-popup='menu'] .item:has-text('Theme')")
    page.click("[data-popup='menu'] .drop.sub .item:has-text('Gruvbox')")
    check(page.evaluate("document.documentElement.dataset.theme") == "gruvbox", "View ▸ Theme ▸ Gruvbox switches the theme")
    shot(page, "shell-gruvbox")
    page.click(".menubar.top [data-menu='View']")
    page.hover("[data-popup='menu'] .item:has-text('Theme')")
    page.click("[data-popup='menu'] .drop.sub .item:has-text('Midnight')")

    # palette ^K: fuzzy, highlighted, runs and records palette.last
    page.keyboard.press("ControlOrMeta+k")
    expect(page.locator("[data-popup='palette']")).to_be_visible()
    page.keyboard.type("gt kan")
    expect(page.locator("[data-popup='palette'] .pitem").first).to_contain_text("Go to: Kanban")
    check(page.locator("[data-popup='palette'] .pitem.sel .hl").count() > 0, "palette highlights matched letters")
    shot(page, "shell-palette")
    page.keyboard.press("Enter")
    expect(page.locator("[data-tab='kanban']")).to_be_visible()
    goto_tab(page, "palette")
    expect_value(page, "palette.last", "Go to: Kanban")
    check(True, "^K ▸ Go to: Kanban runs and sets palette.last")

    # help F1: searchable, "This tab" first
    page.keyboard.press("F1")
    expect(page.locator("[data-popup='help']")).to_be_visible()
    check(page.locator("[data-popup='help'] h4").first.inner_text().upper().startswith("THIS TAB"), "help starts with This tab")
    page.keyboard.type("swimlane-nothing")
    expect(page.locator("[data-popup='help']")).to_contain_text("Nothing matches")
    page.fill("[data-popup='help'] input", "resize")
    expect(page.locator("[data-popup='help'] .hrowk")).to_have_count(1)
    check(True, "help search filters every line")
    page.keyboard.press("Escape")
    page.keyboard.press("ControlOrMeta+g")
    expect(page.locator("[data-popup='help']")).to_be_visible()
    page.keyboard.press("Escape")
    check(True, "^G also opens help")

    # ^R reset with confirm
    goto_tab(page, "select")
    focus(page, "select.status")
    page.keyboard.press("Enter")
    page.keyboard.type("bl")
    page.keyboard.press("Enter")
    expect_value(page, "select.status", "blocked")
    page.keyboard.press("ControlOrMeta+r")
    expect(page.locator("[data-popup='dialog']")).to_contain_text("Reset this tab?")
    page.keyboard.press("n")
    expect(page.locator("[data-popup='dialog']")).to_have_count(0)
    check(page.locator(".vrow[data-key='select.status'] .vv").inner_text() == '"blocked"', "n cancels the reset")
    page.keyboard.press("ControlOrMeta+r")
    page.keyboard.press("y")
    expect_value(page, "select.status", "in_progress")
    check(True, "^R ▸ y resets the tab to defaults")

    # hint bar click runs it; View ▸ Keys panel toggles
    page.click(".hintbar .hint:has-text('Commands')")
    expect(page.locator("[data-popup='palette']")).to_be_visible()
    page.keyboard.press("Escape")
    check(True, "clicking a hint runs it")
    page.click(".menubar.top [data-menu='View']")
    page.click("[data-popup='menu'] .item:has-text('Keys panel')")
    expect(page.locator(".panel.keys")).to_have_count(0)
    page.click(".menubar.top [data-menu='View']")
    page.click("[data-popup='menu'] .item:has-text('Keys panel')")
    expect(page.locator(".panel.keys")).to_have_count(1)
    check(True, "View ▸ Keys panel toggles the panel")

    con.assert_clean()
    b.close()
print("shell ok")
