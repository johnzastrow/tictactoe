"""Write one VHS tape per item in steps.py, plus the tour, into tapes/.

    python gen_tapes.py

The tapes run from docs/demo/screenshots/<lang>/ (make.sh cds there) and
expect DEMO_BIN and DEMO_SERVER in the environment.
"""
import os

from steps import ITEMS, TYPE_MS, TABS

SETTLE = 1500  # ms before and after each still
LEAD_IN = 800  # ms shown before the first step
NO_REPEAT = {"Escape"}  # VHS keys that take no repeat count

HEADER = f"""Set Shell zsh
Set FontSize 26
Set Width 1640
Set Height 960
Set Padding 16
Set Theme "Builtin Dark"
Set TypingSpeed {TYPE_MS}ms
Set Framerate 24
"""


def launch(down):
    """Start the TUI out of frame and move the sidebar to the item's tab."""
    lines = ["Hide", "Type '\"$DEMO_BIN\" tui --server \"$DEMO_SERVER\" --name alice'", "Enter",
             "Sleep 3000ms"]
    if down:
        lines += [f"Down {down}", "Sleep 600ms"]
    return lines + ["Show", f"Sleep {LEAD_IN}ms"]


def quote(text):
    return "`" + text + "`" if '"' in text else '"' + text + '"'


def body(name, steps):
    out = []
    for s in steps:
        if s == "open":
            out.append("# open")
        elif s == "shot":
            out += [f"Sleep {SETTLE}ms", f'Screenshot "raw/tui-{name}.png"', f"Sleep {SETTLE}ms"]
        elif s == "reset":
            out += ["Escape", "Sleep 300ms", "Ctrl+R", "Sleep 500ms", 'Type "y"', "Sleep 800ms"]
        elif s[0] == "k":
            _, key, n = s
            if key in NO_REPEAT or key.startswith("Ctrl+"):
                out += [key] * n
            else:
                out.append(key if n == 1 else f"{key} {n}")
            out.append("Sleep 150ms")
        elif s[0] == "t":
            out.append("Type " + quote(s[1]))
        elif s[0] == "s":
            out.append(f"Sleep {s[1]}ms")
    return out + ["Sleep 500ms"]


def main():
    os.makedirs("tapes", exist_ok=True)
    for name, tab, title, steps in ITEMS:
        lines = [f"# {title} (generated by gen_tapes.py from steps.py; do not edit)",
                 f'Output "tui-{name}.gif"', f'Output "raw/tui-{name}.mp4"', HEADER]
        lines += launch(tab - 1) + body(name, steps)
        with open(f"tapes/{name}.tape", "w") as f:
            f.write("\n".join(lines) + "\n")

    # Tour: walk the sidebar through all 16 tabs
    lines = ["# Tour of the 16 tabs, walking the sidebar with Down (generated by gen_tapes.py)",
             'Output "tui-tour.gif"', HEADER] + launch(0)
    for i, (tab_id, _) in enumerate(TABS, 1):
        # VHS saves a screenshot a moment late: wait before the next key
        lines += ["Sleep 1400ms", f'Screenshot "raw/tour-{i:02d}-{tab_id}.png"', "Sleep 600ms"]
        if i < len(TABS):
            lines += ["Down", "Sleep 300ms"]
    lines.append("Sleep 1000ms")
    with open("tapes/tour.tape", "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {len(ITEMS) + 1} tapes")


if __name__ == "__main__":
    main()
